param([string]$Go = 'go', [string]$Pnpm = 'pnpm', [switch]$Check)

$ErrorActionPreference = 'Stop'
$root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$modules = @{}
$frontend = @{}
$originalOS = $env:GOOS
$originalArch = $env:GOARCH
Push-Location $root
try {
    foreach ($target in @('windows', 'linux')) {
        $env:GOOS = $target
        $env:GOARCH = 'amd64'
        $lines = & $Go list -deps -f '{{if .Module}}{{.Module.Path}}{{end}}' ./cmd/freeagent ./cmd/freeagent-desktop
        if ($LASTEXITCODE -ne 0) { throw "go list failed for $target" }
        foreach ($line in $lines) {
            if ([string]::IsNullOrWhiteSpace($line)) { continue }
            if (-not $modules.ContainsKey($line)) {
                $description = & $Go list -m -json $line
                if ($LASTEXITCODE -ne 0) { throw "go list module failed: $line" }
                $module = ($description -join "`n") | ConvertFrom-Json
                if (-not $module.Main) { $modules[$module.Path] = $module }
            }
        }
    }
    $text = [Text.StringBuilder]::new()
    [void]$text.AppendLine('# Third-Party Notices')
    [void]$text.AppendLine()
    [void]$text.AppendLine('Generated by scripts/update-notices.ps1 from the locked modules compiled')
[void]$text.AppendLine('into the Windows/Linux AMD64 CLI, the Windows desktop shell, and the optional bundled Chat runtime')
    [void]$text.AppendLine('dependencies (including their production dependency closure). Build-only')
    [void]$text.AppendLine('frontend tools are not distributed. The Go standard library carries its')
    [void]$text.AppendLine('own BSD license in the Go distribution. Notices are reproduced below.')
    foreach ($name in ($modules.Keys | Sort-Object)) {
        $module = $modules[$name]
        $files = @(Get-ChildItem -LiteralPath $module.Dir -File |
            Where-Object { $_.Name -match '^(LICENSE|LICENCE|COPYING|NOTICE)([.-].*)?$' } |
            Sort-Object Name)
        if ($files.Count -eq 0) { throw "No license found for $name" }
        [void]$text.AppendLine()
        [void]$text.AppendLine("## $name $($module.Version)")
        foreach ($file in $files) {
            [void]$text.AppendLine()
            [void]$text.AppendLine("### $($file.Name)")
            [void]$text.AppendLine()
            [void]$text.AppendLine('```text')
            [void]$text.AppendLine([IO.File]::ReadAllText($file.FullName).Replace("`r`n", "`n").TrimEnd())
            [void]$text.AppendLine('```')
        }
    }
    $chat = Join-Path $root 'internal/chatui'
    Push-Location $chat
    try {
        $lines = & $Pnpm list --prod --depth Infinity --json
        if ($LASTEXITCODE -ne 0) { throw 'pnpm production dependency listing failed' }
        $projects = @(($lines -join "`n") | ConvertFrom-Json)
        if ($projects.Count -ne 1 -or -not $projects[0].dependencies) {
            throw 'Install the locked Chat dependencies before generating notices'
        }
        function Add-FrontendDependencies($dependencies) {
            foreach ($property in $dependencies.PSObject.Properties) {
                $package = $property.Value
                if (-not $package.path -or -not $package.version) {
                    throw "Installed package metadata missing: $($property.Name)"
                }
                $identity = "$($property.Name)@$($package.version)"
                if (-not $frontend.ContainsKey($identity)) {
                    $frontend[$identity] = $package
                    if ($package.dependencies) { Add-FrontendDependencies $package.dependencies }
                }
            }
        }
        Add-FrontendDependencies $projects[0].dependencies
    } finally {
        Pop-Location
    }
    [void]$text.AppendLine()
    [void]$text.AppendLine('## Bundled Chat Runtime')
    foreach ($identity in ($frontend.Keys | Sort-Object)) {
        $package = $frontend[$identity]
        $metadata = Get-Content -LiteralPath (Join-Path $package.path 'package.json') -Raw | ConvertFrom-Json
        if ("$($metadata.name)@$($metadata.version)" -ne $identity) {
            throw "Installed package identity mismatch: $identity"
        }
        $files = @(Get-ChildItem -LiteralPath $package.path -File |
            Where-Object { $_.Name -match '^(LICENSE|LICENCE|COPYING|NOTICE)([.-].*)?$' } |
            Sort-Object Name)
        if ($files.Count -eq 0) { throw "No license found for $identity" }
        [void]$text.AppendLine()
        [void]$text.AppendLine("### $identity")
        foreach ($file in $files) {
            [void]$text.AppendLine()
            [void]$text.AppendLine("#### $($file.Name)")
            [void]$text.AppendLine()
            [void]$text.AppendLine('```text')
            [void]$text.AppendLine([IO.File]::ReadAllText($file.FullName).Replace("`r`n", "`n").TrimEnd())
            [void]$text.AppendLine('```')
        }
    }
    $destination = Join-Path $root 'THIRD_PARTY_NOTICES.md'
    $generated = $text.ToString().Replace("`r`n", "`n")
    if ($Check) {
        if ([IO.File]::ReadAllText($destination).Replace("`r`n", "`n") -ne $generated) {
            throw 'THIRD_PARTY_NOTICES.md is stale; run scripts/update-notices.ps1'
        }
    } else {
        [IO.File]::WriteAllText($destination, $generated, [Text.UTF8Encoding]::new($false))
    }
} finally {
    Pop-Location
    $env:GOOS = $originalOS
    $env:GOARCH = $originalArch
}
